/// Replay a seed with the greedy auto-player and emit the `adb` commands that
/// perform the same moves on a device.
///
/// This exists because the core is a pure seeded state machine: given the seed
/// shown in the game's settings sheet, this script computes the exact piece
/// sequence and the exact moves the device will see. Driving those moves back
/// in through `adb input swipe` turns a blind tap-and-hope session into a
/// deterministic one, and lets the run's real outcome be compared against a
/// prediction made before a single tap.
///
/// It lives under `test/` and runs through `flutter test` because the run
/// controller reaches into Flutter (haptics, preferences, ChangeNotifier), so
/// a plain `dart run` cannot resolve its imports.
///
/// Usage:
///   flutter test test/device/device_script_test.dart ///     --dart-define=SEED=1KMWBAN --dart-define=FAULT=thin_place
///
/// The seed code is the base-36 string the game shows in its settings sheet.
library;

import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

import 'package:loomcraft/core/board.dart';
import 'package:loomcraft/core/shapes.dart';
import 'package:loomcraft/core/types.dart';
import 'package:loomcraft/data/tuning.dart';
import 'package:loomcraft/game/account.dart';
import 'package:loomcraft/game/run_controller.dart';
import 'package:loomcraft/platform/haptics.dart';
import 'package:loomcraft/platform/storage.dart';
import 'package:loomcraft/render/theme.dart';

/* ---------------- device geometry, measured from a screenshot ------------ */
//
// Physical pixels on the emulator: 720x1600 at density 320, so 360x800 dp.
// Measured once off a board screenshot rather than re-derived, because the
// layout is deterministic for a given device and a wrong guess here is
// indistinguishable from a bug in the game.
const double cellPx = 83.0;
const double boardLeftPx = 27.5;
const double boardTopPx = 513.5;
const List<double> slotCentreXPx = [132, 360, 588];
const double slotCentreYPx = 1356;

/// The piece floats 56 logical px above the finger (spec §7), and this device
/// is 2 physical px per logical px.
const double liftPx = 56.0 * 2;

const _seedCode = String.fromEnvironment('SEED', defaultValue: '1KMWBAN');
const _faultId = String.fromEnvironment('FAULT', defaultValue: 'thin_place');
const _maxMoves = int.fromEnvironment('MOVES', defaultValue: 40);

void main() {
  test(
    'replays the device seed and writes the adb script',
    () async {
      await _generate();
    },
    // A generator, not an assertion: it writes files, so it stays out of an
    // ordinary `flutter test` run and only fires when a seed is handed to it.
    skip: _hasSeed ? false : 'pass --dart-define=SEED=<code> to generate',
    timeout: const Timeout(Duration(minutes: 2)),
  );
}

const bool _hasSeed = bool.hasEnvironment('SEED');

Future<void> _generate() async {
  final seed = parseSeedCode(_seedCode);
  if (seed == null) throw ArgumentError('not a seed code: $_seedCode');
  final faultId = _faultId;
  final maxMoves = _maxMoves;

  Future<Map<String, dynamic>> read(String name) async =>
      jsonDecode(await File('data/$name').readAsString())
          as Map<String, dynamic>;

  final tuning = Tuning(
    curve: parseCurve(await read('curve.json')),
    economy: parseEconomy(await read('economy.json')),
    powers: parsePowers(await read('powers.json')),
    faults: parseFaults(await read('faults.json')),
  );

  // A freshly cleared app: tier 1 only, no upgrades. `runsStarted: 1` because
  // the script is a walkthrough of ordinary play — a literal first install
  // gets a level 1 pre-arranged to teach, which is a different board.
  final account = Account(runsStarted: 1);
  final c = RunController(
    tuning: tuning,
    account: account,
    storage: MemoryStorage(),
    haptics: Haptics(enabled: false),
    seedSource: () => seed,
  );
  c.begin();
  c.chooseFault(faultId);

  final lines = <String>[];
  void emit(String s) => lines.add(s);

  emit('#!/bin/sh');
  emit('# Generated by tool/device_script.dart');
  emit('# seed $_seedCode ($seed), fault $faultId');
  emit('D="adb -s emulator-5554"');
  emit('shot() { \$D exec-out screencap -p > "\$1"; }');
  emit('');

  var move = 0;
  var firstClearAt = -1;
  var stageClearAt = -1;

  while (move < maxMoves && c.phase == GamePhase.placing) {
    final best = _bestMove(c);
    if (best == null) {
      emit('# no legal move found at move $move');
      break;
    }
    move++;

    // Rotating is a tap on the slot: short, still, under tapMs.
    final item = c.tray[best.slot]!;
    var spins = 0;
    while (c.tray[best.slot]!.rotation != best.rotation && spins++ < 8) {
      emit('\$D shell input tap ${slotCentreXPx[best.slot].round()} '
          '${slotCentreYPx.round()}   # rotate slot ${best.slot}');
      emit('sleep 0.35');
      c.rotate(best.slot);
    }

    final cells = cellsOf(item.shapeId, best.rotation);
    final e = extent(cells);
    final centreX = boardLeftPx + best.ax * cellPx + e.w * cellPx / 2;
    final centreY = boardTopPx + best.ay * cellPx + e.h * cellPx / 2;
    final fingerY = centreY + liftPx;

    emit('# move $move: ${shapeName(item.shapeId)} '
        '-> (${best.ax},${best.ay})');
    emit('\$D shell input swipe ${slotCentreXPx[best.slot].round()} '
        '${slotCentreYPx.round()} ${centreX.round()} ${fingerY.round()} 800');
    emit('sleep 0.6');

    final before = c.ladder.score.total;
    final ok = c.place(best.slot, Anchor(best.ax, best.ay));
    if (!ok) {
      emit('# REFUSED by the controller — aborting');
      break;
    }
    final gained = c.ladder.score.total - before;

    if (best.lines > 0 && firstClearAt < 0) {
      firstClearAt = move;
      emit('shot "\$SHOTS/clear-$move.png"   '
          '# ${best.lines} line(s) cleared here');
    }
    if (c.phase != GamePhase.placing && stageClearAt < 0) {
      stageClearAt = move;
      emit('shot "\$SHOTS/levelclear-$move.png"');
    }
    emit('# -> +$gained, total ${c.ladder.score.total}, '
        'combo x${c.ladder.score.multiplier.toStringAsFixed(2)}, '
        '${c.ladder.placementsLeft} moves left, phase ${c.phase.name}');
    emit('');
  }

  // ---- The prediction, printed for comparison with the device ------------
  final predicted = {
    'seed': seed,
    'seedCode': _seedCode,
    'fault': faultId,
    'moves': move,
    'firstClearAtMove': firstClearAt,
    'levelClearAtMove': stageClearAt,
    'phase': c.phase.name,
    'stage': c.ladder.stage,
    'stageScore': c.ladder.stageScore,
    'target': c.ladder.target,
    'total': c.ladder.score.total,
    'multiplier': c.ladder.score.multiplier,
    'movesLeft': c.ladder.placementsLeft,
    'draftOptions': [for (final d in c.draftOptions) d.id],
    'boardFilled': countFilled(c.board),
  };

  await File('tool/out/device_script.sh').create(recursive: true);
  await File('tool/out/device_script.sh').writeAsString(lines.join('\n'));
  await File('tool/out/prediction.json')
      .writeAsString(const JsonEncoder.withIndent('  ').convert(predicted));

  stdout.writeln(const JsonEncoder.withIndent('  ').convert(predicted));
}

/* ---------------- a greedy move, same rule as the sim harness ------------ */

class _Move {
  _Move(this.slot, this.rotation, this.ax, this.ay, this.lines);
  final int slot;
  final int rotation;
  final int ax;
  final int ay;
  final int lines;
}

int _contact(Board b, ShapeCells cells, int ax, int ay) {
  final own = <int>{for (final (cx, cy) in cells) (ay + cy) * b.w + (ax + cx)};
  var n = 0;
  const deltas = <Coord>[(1, 0), (-1, 0), (0, 1), (0, -1)];
  for (final (cx, cy) in cells) {
    for (final (dx, dy) in deltas) {
      final nx = ax + cx + dx;
      final ny = ay + cy + dy;
      if (nx < 0 || ny < 0 || nx >= b.w || ny >= b.h) {
        n++;
      } else if (!own.contains(ny * b.w + nx) && cellAt(b, nx, ny) != 0) {
        n++;
      }
    }
  }
  return n;
}

_Move? _bestMove(RunController c) {
  _Move? best;
  var bestScore = double.negativeInfinity;
  for (var slot = 0; slot < c.tray.length; slot++) {
    final item = c.tray[slot];
    if (item == null) continue;
    final s = shape(item.shapeId);
    for (var r = 0; r < s.rotations.length; r++) {
      final cells = cellsOf(item.shapeId, r);
      final e = extent(cells);
      for (var ay = 0; ay <= c.board.h - e.h; ay++) {
        for (var ax = 0; ax <= c.board.w - e.w; ax++) {
          if (!fits(c.board, cells, ax, ay)) continue;
          final result = resolvePlacement(
            c.board,
            cells,
            ax,
            ay,
            cells.length,
            axes: c.faultEffects.axes,
          );
          final score = result.lines * 10000 +
              _contact(c.board, cells, ax, ay) * 30 -
              countFilled(result.board) * 4;
          if (score > bestScore) {
            bestScore = score.toDouble();
            best = _Move(slot, r, ax, ay, result.lines);
          }
        }
      }
    }
  }
  return best;
}
